// writeAPI 把一组 (path -> content) 写入临时根，返回根目录。
func writeAPI(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, content := range files {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", rel, err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", rel, err)
		}
	}
	return root
}

// apisvrTree 构造一个最小但覆盖关键路径的 apisvr 形态目录：
//   - 入口 import 多级（api.api -> system.api -> system/role.api）
//   - prefix 前导 '/' 归一化（oss 风格的 "open/oss"）
//   - route-level authType 覆盖 server defaultAuthType
//   - route-level isNeedAuth 覆盖
//   - middleware 顺序
//   - 空 request/response
//   - 同一路由在不同 @server group 下（去重行为）
//   - 游离文件（service 块但未被 import）
func apisvrTree(t *testing.T) string {
	root := t.TempDir()
	files := map[string]string{
		// 入口
		"service/apisvr/http/api.api": `syntax = "v1"
import "system.api"
`,
		"service/apisvr/http/system.api": `syntax = "v1"
import "system/role.api"
import "shared.api"
`,
		// 共享类型（多级 import 依赖）
		"service/apisvr/http/shared.api": `syntax = "v1"
type (
	WithID {
		ID int64 ` + "`json:\"id,optional\"`" + `
	}
)
`,
		// 角色路由：server defaultAuthType=supper，但 route @doc authType=admin 覆盖
		"service/apisvr/http/system/role.api": `syntax = "v1"
@server(
	group: system/role/info
	prefix: /api/v1/system/role/info
	accessGroup: "角色管理"
	defaultAuthType: "supper"
	defaultNeedAuth: "true"
	middleware: CheckTokenWare,InitCtxsWare
)
service api {
	@doc(
		summary: "添加角色"
		description: "在当前租户下新建角色，含名称与状态"
		authType: "admin"
		isNeedAuth: "false"
		resource: "role"
		action: "create"
		group: "system/role/info"
		recordLogMode: "2"
	)
	@handler create
	post /create (RoleInfo) returns (WithID)

	@doc(
		summary: "获取角色列表"
		description: "按名称分页查询当前租户的角色清单"
		authType: "supper"
		resource: "role"
		action: "view"
		group: "system/role/info"
		recordLogMode: "1"
	)
	@handler index
	post /index (RoleInfoIndexReq) returns (RoleInfoIndexResp)
}
type (
	RoleInfo { Name string ` + "`json:\"name\"`" + ` }
	RoleInfoIndexReq { Name string ` + "`json:\"name,optional\"`" + ` }
	RoleInfoIndexResp { List []*RoleInfo ` + "`json:\"list\"`" + ` }
)
`,
		// 游离文件：prefix 无前导 '/'，空 response
		"service/apisvr/http/system/oss.api": `syntax = "v1"
@server(
	group: open/oss
	prefix: open/oss
)
service api {
	@doc(
		summary: "上传"
		description: "按签名校验后接收文件并写入对象存储"
		authType: "all"
		resource: "oss"
		action: "upload"
		group: "open/oss"
		recordLogMode: "1"
	)
	@handler upload
	put /upload (UploadReq) returns ()
	@doc(
		summary: "下载"
		description: "按签名校验后从对象存储下载文件"
		authType: "all"
		resource: "oss"
		action: "download"
		group: "open/oss"
		recordLogMode: "1"
	)
	@handler downLoad
	get /download (DownloadReq) returns ()
}
type (
	UploadReq { Sign string ` + "`form:\"sign\"`" + ` }
	DownloadReq { Sign string ` + "`form:\"sign\"`" + ` }
)
`,
		// 生成的 routes.go（仅注册 create，验证 RegisteredRoutes）。
		"service/apisvr/internal/handler/routes.go": `package handler
import (
	"net/http"
	"gitee.com/ming-iot/saas/service/apisvr/internal/handler/system/role/info"
	"gitee.com/ming-iot/saas/service/apisvr/internal/svc"
	"github.com/zeromicro/go-zero/rest"
)
func RegisterHandlers(server *rest.Server, serverCtx *svc.ServiceContext) {
	server.AddRoutes(
		rest.WithMiddlewares(
			[]rest.Middleware{serverCtx.CheckTokenWare, serverCtx.InitCtxsWare},
			[]rest.Route{
				{
					Method:  http.MethodPost,
					Path:    "/create",
					Handler: info.CreateHandler(serverCtx),
				},
			}...,
		),
		rest.WithPrefix("/api/v1/system/role/info"),
	)
}
`,
		// 历史生成的 types.go（兜底缺失引用类型；这里留空文件即可）。
		"service/apisvr/internal/types/types.go": `package types
`,
	}
	for rel, content := range files {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", rel, err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", rel, err)
		}
	}
	return root
}

