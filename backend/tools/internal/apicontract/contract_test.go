func TestRealBackendCounts(t *testing.T) {
	if testing.Short() {
		t.Skip("requires real core tree")
	}
	_, source, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("locate test source")
	}
	coreRoot := filepath.Join(filepath.Dir(source), "..", "..", "..", "saas")
	snaps, err := LoadBackend(coreRoot)
	if err != nil {
		t.Fatalf("LoadBackend: %v", err)
	}
	want := map[string]struct{ def, reach, reg, detach int }{
		"apisvr":  {237, 235, 235, 2},
		"datasvr": {7, 7, 7, 0},
	}
	for svc, w := range want {
		s := snaps[svc]
		if len(s.Defined) != w.def || len(s.Reachable) != w.reach ||
			len(s.Registered) != w.reg || len(s.Detached) != w.detach {
			t.Errorf("%s: defined=%d reachable=%d registered=%d detached=%d; want %+v",
				svc, len(s.Defined), len(s.Reachable), len(s.Registered), len(s.Detached), w)
		}
	}
	// 源闭包：AppleAppConfig 已补回，UndefinedTypes 应为空。
	for svc, s := range snaps {
		if len(s.UndefinedTypes) != 0 {
			t.Errorf("%s undefined types: %v", svc, s.UndefinedTypes)
		}
	}
}

