func TestLoadServiceAuthOverride(t *testing.T) {
	root := apisvrTree(t)
	b := Backends(root)["apisvr"]
	snap, err := LoadService(b)
	if err != nil {
		t.Fatalf("LoadService: %v", err)
	}
	// create：route @doc authType=admin 覆盖 server defaultAuthType=supper；
	// route @doc isNeedAuth=false 覆盖 server defaultNeedAuth=true。
	authByRoute := map[string]Authorization{}
	for _, a := range snap.Authorization {
		authByRoute[a.FullPath] = a
	}
	if a := authByRoute["/api/v1/system/role/info/create"]; a.EffectiveAuthType != "admin" {
		t.Errorf("create auth=%q want admin (route override)", a.EffectiveAuthType)
	}
	if a := authByRoute["/api/v1/system/role/info/create"]; a.EffectiveNeedAuth != false {
		t.Errorf("create needAuth=%v want false (route override)", a.EffectiveNeedAuth)
	}
	// index：无 route isNeedAuth，回退 server defaultNeedAuth=true。
	if a := authByRoute["/api/v1/system/role/info/index"]; a.EffectiveNeedAuth != true {
		t.Errorf("index needAuth=%v want true (server default)", a.EffectiveNeedAuth)
	}
	// index：route @doc authType=supper。
	if a := authByRoute["/api/v1/system/role/info/index"]; a.EffectiveAuthType != "supper" {
		t.Errorf("index auth=%q want supper", a.EffectiveAuthType)
	}
	// managedByAccess：role 有 accessGroup -> true；oss 无 -> false。
	if a := authByRoute["/api/v1/system/role/info/create"]; !a.ManagedByAccess {
		t.Errorf("role create should be managed by access")
	}
	if a := authByRoute["/open/oss/upload"]; a.ManagedByAccess {
		t.Errorf("oss upload should not be managed by access")
	}
	// operType：/create -> add；/index -> find。
	if a := authByRoute["/api/v1/system/role/info/create"]; a.EffectiveOperType != "add" {
		t.Errorf("create operType=%q want add", a.EffectiveOperType)
	}
	if a := authByRoute["/api/v1/system/role/info/index"]; a.EffectiveOperType != "find" {
		t.Errorf("index operType=%q want find", a.EffectiveOperType)
	}
}

